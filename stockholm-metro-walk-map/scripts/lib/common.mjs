export function readJson(file, fallback) {
  if (!fs.existsSync(file)) {
    if (fallback !== undefined) return fallback;
    throw new Error(`Missing input file: ${path.relative(ROOT, file)}`);
  }
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (err) {
    throw new Error(`Invalid JSON in ${path.relative(ROOT, file)}: ${err.message}`);
  }
}

/** Atomic write (temp file + rename) so an interrupted run never leaves half a file. */
export function writeFileAtomic(file, contents) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = path.join(path.dirname(file), `.tmp-${path.basename(file)}-${process.pid}`);
  fs.writeFileSync(tmp, contents);
  fs.renameSync(tmp, file);
}

export function writeJson(file, data, pretty = true) {
  writeFileAtomic(file, JSON.stringify(data, null, pretty ? 2 : 0) + '\n');
}

/**
 * Write browser data as a classic script assigning a global, so the app also
 * works when index.html is opened directly from disk (file:// cannot fetch()).
 */
export function writeBrowserData(file, globalName, data) {
  const json = JSON.stringify(data)
    .replace(/</g, '\\u003c')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
  writeFileAtomic(file, `/* Generated by the stockholm-metro-walk-map data pipeline. Do not edit. */\nwindow.${globalName} = ${json};\n`);
}

export function rel(file) {
  return path.relative(ROOT, file);
}

export function parseArgs(argv) {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith('--')) {
      const [k, v] = a.slice(2).split('=');
      if (v !== undefined) out[k] = v;
      else if (argv[i + 1] && !argv[i + 1].startsWith('--')) out[k] = argv[++i];
      else out[k] = true;
    } else out._.push(a);
  }
  return out;
}

